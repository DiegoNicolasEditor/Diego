/* =========================================================
   Motor de tradução — não precisa editar abaixo
   ========================================================= */
(function () {
  const STORAGE_KEY = "dyo-lang-v2";
  let currentLang = localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "pt";

  function translateElements(lang) {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const entry = window.DYO_I18N[key];
      if (!entry || entry[lang] === undefined) return;
      const text = entry[lang];
      if (/<[a-z]/i.test(text)) {
        el.innerHTML = text;
      } else {
        el.textContent = text;
      }
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
      const key = el.getAttribute("data-i18n-aria-label");
      const entry = window.DYO_I18N[key];
      if (entry && entry[lang] !== undefined) {
        el.setAttribute("aria-label", entry[lang]);
      }
    });
  }

  function applyLang(lang) {
    currentLang = lang;
    localStorage.setItem(STORAGE_KEY, lang);

    // Atualiza o atributo lang do HTML
    document.documentElement.lang = lang === "pt" ? "pt-BR" : "en";
    document.title = window.DYO_I18N["meta.title"][lang];
    const description = document.querySelector('meta[name="description"]');
    if (description) description.setAttribute("content", window.DYO_I18N["meta.description"][lang]);

    translateElements(lang);

    // Exibe a bandeira do idioma para o qual o botão vai alternar
    const label = document.getElementById("lang-label");
    if (label) {
      label.querySelectorAll("[data-target-lang]").forEach((option) => {
        option.classList.toggle("is-target", option.dataset.targetLang !== lang);
      });
    }

    const button = document.getElementById("lang-toggle");
    if (button) {
      button.setAttribute(
        "aria-label",
        lang === "pt" ? "Mudar para inglês" : "Switch to Portuguese"
      );
      button.title = lang === "pt" ? "Mudar para inglês" : "Switch to Portuguese";
    }

    document.dispatchEvent(
      new CustomEvent("dyo:languagechange", { detail: { lang } })
    );
  }

  document.addEventListener("dyo:contentready", () => {
    translateElements(currentLang);
  });

  // Botão de troca
  function initLangToggle() {
    const btn = document.getElementById("lang-toggle");
    if (!btn) return;
    btn.addEventListener("click", () => {
      applyLang(currentLang === "pt" ? "en" : "pt");
    });
    // Aplica o idioma salvo ao carregar
    applyLang(currentLang);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", initLangToggle);
  } else {
    initLangToggle();
  }
})();
